export function initials(s: string) {
  const w = s.replace(/@.*/, "").split(/[\s._-]+/).filter(Boolean);
  return ((w[0]?.[0] || "?") + (w.length > 1 ? w[w.length - 1][0] : w[0]?.[1] || "")).toUpperCase();
}
